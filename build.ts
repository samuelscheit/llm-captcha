// Builds the page bundle (shared by every driver), the extension and the CDP library into
// $OUT_DIR (default dist/). The updater builds into a staging directory and swaps it in.
// Bun's own bundler, so it also runs as the `prepare` script of a git install, which gets no
// devDependencies.
import { execSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const out = process.env.OUT_DIR ?? "dist";

type Options = Omit<Bun.BuildConfig, "outdir"> & { outfile?: string; outdir?: string };

/** One Bun.build call; throws with the bundler's messages when it fails. */
async function build({ outfile, outdir, ...options }: Options): Promise<void> {
  const result = await Bun.build({
    target: "browser",
    minify: { syntax: true, whitespace: false, identifiers: false },
    ...options,
    ...(outfile ? { outdir: outfile.slice(0, outfile.lastIndexOf("/")), naming: outfile.slice(outfile.lastIndexOf("/") + 1) } : { outdir }),
  });
  if (!result.success) throw new AggregateError(result.logs, "build failed");
}

// Build identity: the commit, marked dirty with local changes. The extension compares the id it
// runs with dist/extension/build.json and reloads itself when the updater rebuilt it.
const git = (cmd: string) => execSync(`git ${cmd}`, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
let commit = "unknown";
try {
  commit = git("rev-parse --short HEAD") + (git("status --porcelain -- src build.ts package.json") ? "-dirty" : "");
} catch {}
const buildInfo = { commit, id: `${commit}@${new Date().toISOString()}` };
writeFileSync("src/core/build-info.generated.ts", `// Generated by build.ts. Do not edit.\nexport const BUILD = ${JSON.stringify(buildInfo)};\n`);

// 1. Page code, injected by CDP drivers into isolated worlds.
await build({ entrypoints: ["src/page/entry.ts"], format: "iife", outfile: `${out}/page.js` });
writeFileSync(
  "src/cdp/page-source.generated.ts",
  `// Generated by build.ts from src/page/entry.ts. Do not edit.\nexport const PAGE_SOURCE = ${JSON.stringify(readFileSync(`${out}/page.js`, "utf8"))};\n`,
);

// 2. Extension.
mkdirSync(`${out}/extension`, { recursive: true });
await build({ entrypoints: ["src/extension/background.ts", "src/extension/options.ts"], format: "esm", outdir: `${out}/extension` });
// Content scripts are classic scripts.
await build({ entrypoints: ["src/extension/content.ts"], format: "iife", outfile: `${out}/extension/content.js` });
cpSync("src/extension/static", `${out}/extension`, { recursive: true });
writeFileSync(`${out}/extension/build.json`, `${JSON.stringify(buildInfo)}\n`);

// 3. CDP library for Playwright / Puppeteer / raw CDP.
await build({ entrypoints: ["src/cdp/index.ts"], format: "esm", target: "node", outfile: `${out}/cdp/index.js`, packages: "external" });
console.log(`built ${out}/ (${buildInfo.id})`);
